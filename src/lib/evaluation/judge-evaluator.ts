import type { Database } from 'better-sqlite3';

/**
 * Result of a judge decision evaluation.
 */
export interface JudgeDecisionResult {
  decision: 'agree' | 'disagree';
  reasoning: string;
}

/**
 * Structure of the parsed judge model response.
 */
export interface JudgeResponseParsed {
  decision: 'agree' | 'disagree';
  reasoning: string;
}

/**
 * Parse judge model response from JSON.
 * Expected format: {decision: "agree"|"disagree", reasoning: string}
 * @param response - Raw string response from the judge model
 * @returns Parsed judge response object
 * @throws Error if response is invalid JSON or missing required fields
 */
export function parseJudgeResponse(response: string): JudgeResponseParsed {
  try {
    const parsed = JSON.parse(response);

    // Validate decision field
    if (!parsed.decision) {
      throw new Error('Invalid judge response: missing decision field');
    }

    if (parsed.decision !== 'agree' && parsed.decision !== 'disagree') {
      throw new Error(`Invalid judge decision: ${parsed.decision}. Must be "agree" or "disagree"`);
    }

    return {
      decision: parsed.decision as 'agree' | 'disagree',
      reasoning: parsed.reasoning || '',
    };
  } catch (error) {
    if (error instanceof Error && error.message.includes('Invalid judge')) {
      throw error;
    }
    throw new Error(
      `Failed to parse judge response: ${error instanceof Error ? error.message : 'Unknown error'}`
    );
  }
}

