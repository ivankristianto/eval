/**
 * Format the judge prompt with context.
 * Includes input, expected output, and suggested output for evaluation.
 * @param input - The original task input
 * @param expectedOutput - Ground truth output
 * @param suggestedOutput - Model generated output
 * @param judgePrompt - Base judge instructions
 * @returns Full formatted prompt for the judge model
 */
export function formatJudgePrompt(
  input: string,
  expectedOutput: string,
  suggestedOutput: string,
  judgePrompt: string
): string {
  return `${judgePrompt}

**Input/Question:**
${input}

**Expected Output:**
${expectedOutput}

**Suggested Output to Evaluate:**
${suggestedOutput}

**Your Task:**
Evaluate whether the Suggested Output meets the quality and correctness criteria defined in the Expected Output. Respond in JSON format with the following structure:

{
  "decision": "agree" | "disagree",
  "reasoning": "Explain your decision"
}

- Use "agree" if the Suggested Output meets or exceeds the Expected Output quality
- Use "disagree" if the Suggested Output fails to meet the Expected Output criteria
- Reasoning should explain your decision clearly`;
}

/**
 * Store a judge decision to the database.
 * @param db - Database instance
 * @param iterationId - Iteration ID
 * @param trainingPairId - Training pair ID
 * @param generatedOutput - The output that was judged
 * @param decision - The judge's decision result
 * @param resultId - Optional evaluation result ID
 * @returns Unique ID of the stored decision record
 */
export function storeJudgeDecision(
  db: Database,
  iterationId: string,
  trainingPairId: string,
  generatedOutput: string,
  decision: JudgeDecisionResult,
  resultId?: string
): string {
  const id = crypto.randomUUID();

  db.prepare(
    `
    INSERT INTO judge_decisions
    (id, iteration_id, training_pair_id, result_id, generated_output,
     judge_decision, judge_reasoning, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
  `
  ).run(
    id,
    iterationId,
    trainingPairId,
    resultId || null,
    generatedOutput,
    decision.decision,
    decision.reasoning,
    new Date().toISOString()
  );

  return id;
}
